const chev = () => { const c = icon('chevron'); c.classList.add('chev'); return c; };

export function renderResults(main: HTMLElement, ctx: Ctx): void {
  const r = state.result;
  if (!r) { ctx.go('home'); return; }
  const sum = summarise(r);
  const findings = allFindings(r);
  const simulated = r.provenance.kind === 'simulated';

  const page = h('div', { class: 'wrap results' });
  main.append(h('section', { class: 'page results-page' }, page));

  page.append(provenance(r));
  page.append(summaryHeader(r, sum.usable, sum.verdict, sum.sentence));

  if (!sum.usable) {
    page.append(failurePanel(r, ctx));
  }

  if (sum.usable && findings.length) {
    const list = h('div', { class: 'findings' });
    for (const f of findings) list.append(findingBlock(r, f, !sum.usable));
    page.append(h('section', { 'aria-labelledby': 'findings-title' },
      h('h2', { id: 'findings-title', class: 'section-title' }, 'Findings'),
      list));
  }

  if (sum.usable) page.append(limitsBlock(simulated));
  if (r.pre) page.append(technicalSection(r));
  page.append(actionsRow(ctx, simulated));
}

function provenance(r: AnalysisResult): HTMLElement {
  if (r.provenance.kind === 'simulated') {
    const c = SYNTH_CASES.find((x) => x.id === (r.provenance as { caseId: string }).caseId);
    return h('div', { class: 'provenance simulated', role: 'note' }, icon('flask'),
      h('div', {}, h('strong', {}, `Simulated recording: ${c?.label ?? 'test camera feed'}`),
        'Generated by a pulse-wave model and analysed exactly like a live recording. These results describe the model, not a person.'));
  }
  return h('div', { class: 'provenance measured', role: 'note' }, icon('camera'),
    h('div', {}, h('strong', {}, 'Measured with this phone’s camera'),
      `Recorded ${new Date(r.analysedAt).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' })}. Results describe this one-minute recording only.`));
}

function summaryHeader(r: AnalysisResult, usable: boolean, verdict: string, sentence: string): HTMLElement {
  const level = usable ? (r.quality!.issues.some((i) => i.severity === 'warn') ? 'fair' : 'good') : 'poor';
  const head = h('header', { class: `summary ${usable ? 'ok' : 'fail'}` },
    h('div', { class: 'summary-verdict' },
      h('span', { class: `verdict-icon ${level}` }, statusIcon(level)),
      h('div', {},
        h('h1', { class: 'summary-title' }, verdict),
        h('p', { class: 'summary-sentence' }, sentence),
      ),
    ),
  );
  if (usable && r.hrv && r.score && r.morphology) {
    const pattern = shapePattern(r);
    const shapeWord = { separate: 'Two distinct waves', shoulder: 'Second wave as a shoulder', merged: 'Waves merged' }[pattern!];
    head.append(h('dl', { class: 'readouts' },
      readout('Heart rate', String(Math.round(r.hrv.heartRateBpm)), 'beats/min', '#finding-rate'),
      readout('Steady signal', String(Math.round(cleanSeconds(r))), `of ${Math.round(analysedSeconds(r))} s`, '#finding-quality'),
      readout('Pulse shape', shapeWord, '', '#finding-shape', true),
      readout('Stiffness indicator', `${r.score.band[0].toUpperCase()}${r.score.band.slice(1)} range`, '', '#finding-stiffness', true, true),
    ));
  }
  return head;
}

function readout(label: string, value: string, unit: string, href: string, word = false, experimental = false): HTMLElement {
  return h('div', { class: 'readout' },
    h('dt', {}, label),
    h('dd', {}, h('a', { href, onclick: (e: Event) => { e.preventDefault(); document.querySelector(href)?.scrollIntoView({ behavior: 'smooth' }); } },
      h('span', { class: word ? 'readout-word' : 'readout-num num' }, value),
      unit ? h('span', { class: 'readout-unit' }, unit) : null),
      experimental ? h('div', {}, h('span', { class: 'tag-exp small' }, 'Experimental')) : null),
  );
}

function failurePanel(r: AnalysisResult, ctx: Ctx): HTMLElement {
  const sum = summarise(r);
  const sim = r.provenance.kind === 'simulated';
  const panel = h('section', { class: 'panel failure', 'aria-labelledby': 'fix-title' },
    h('h2', { id: 'fix-title', class: 'panel-title' }, 'How to get a usable recording'),
    h('ol', { class: 'fix-list' }, ...sum.problems.map((p) => h('li', {}, p.fix))),
    h('div', { class: 'actions' },
      h('button', { class: 'btn', onclick: () => ctx.go(sim ? 'demo' : 'setup') }, icon('retry'), sim ? 'Choose another demo' : 'Record again'),
    ),
  );
  const wrap = h('div', { class: 'failure-stack' }, panel);
  if (r.pre && r.quality) {
    const q = qualityFinding(r);
    const chart = h('div', { class: 'chart' });
    wrap.append(h('section', { class: 'failure-evidence', 'aria-labelledby': 'where-title' },
      h('h2', { id: 'where-title', class: 'section-title' }, 'Where the signal was disturbed'),
      h('figure', { class: 'evidence' }, chart, h('figcaption', {},
        h('strong', {}, 'The whole recording. '),
        'Red marks are heartbeats VasoScan found. Hatched stretches were disturbed and could not be used. At least 30 seconds of steady signal are needed for any measurement.')),
      h('dl', { class: 'metrics' }, ...q.metrics.map((m) => h('div', {},
        h('dt', {}, m.label),
        h('dd', {}, h('span', { class: `value ${/^\d|^-\d/.test(m.value) ? 'num' : 'word'}` }, m.value), m.unit ? h('span', { class: 'unit' }, m.unit) : null,
          m.note ? h('span', { class: 'note' }, m.note) : null))))),
    );
    queueMicrotask(() => responsive(chart, (w) => timelineChart(r, w)));
  }
  if (!sim) wrap.append(diagnostics(r));
  return wrap;
}

/** What the camera saw, so a failed recording can be understood rather than guessed at. */
function diagnostics(r: AnalysisResult): HTMLElement {
  const frames = state.frames;
  const n = frames.length || 1;
  const counts = { ok: 0, uncovered: 0, dark: 0, overexposed: 0 };
  for (const f of frames) counts[classifyFrame(f)]++;
  const avg = (k: 'r' | 'g' | 'b') => Math.round(frames.reduce((a, f) => a + f[k], 0) / n);
  const pct = (v: number) => `${Math.round((v / n) * 100)}%`;
  const rows: Array<[string, string]> = [
    ['Frames with finger detected', pct(counts.ok)],
    ['Frames too dark', pct(counts.dark)],
    ['Frames not covered', pct(counts.uncovered)],
    ['Average colour (red, green, blue)', `${avg('r')}, ${avg('g')}, ${avg('b')}`],
    ['Camera frame rate', r.quality ? `${r.quality.metrics.frameRate.toFixed(1)} frames/s` : '–'],
    ['Flashlight', state.meta?.torch === 'on' ? 'On' : 'Could not be switched on by the browser'],
    ['Brightness changes corrected', String(r.pre?.exposureSteps.length ?? 0)],
  ];
  return h('details', { class: 'disclose diag' },
    h('summary', {}, h('span', {}, h('span', { class: 's-title' }, 'What the camera saw'), h('span', { class: 's-sub' }, 'Details that help explain why the recording failed')), chev()),
    h('div', { class: 'd-body' }, table(['Check', 'Result'], rows), downloadButtons(r)),
  );
}

function findingBlock(r: AnalysisResult, f: Finding, failed: boolean): HTMLElement {
  const figure = evidenceFor(r, f, failed);
  const art = h('article', { class: `finding finding-${f.id}`, id: `finding-${f.id}`, 'aria-labelledby': `ft-${f.id}` },
    h('div', { class: 'finding-text' },
      h('div', { class: 'finding-head' },
        h('h3', { id: `ft-${f.id}`, class: 'finding-title' }, f.title),
        h('span', { class: 'finding-tags' },
          h('span', { class: `status ${f.status.level}` }, statusIcon(f.status.level), f.status.label),
          f.experimental ? h('span', { class: 'tag-exp' }, icon('flask'), 'Experimental') : null),
      ),
      h('p', { class: 'takeaway' }, f.takeaway),
      h('p', { class: 'explanation' }, f.explanation),
      h('div', { class: `context${f.experimental ? ' experimental' : ''}` }, h('h4', {}, f.experimental ? 'Read this before using the number' : 'Why this matters'), h('p', {}, f.context)),
      h('dl', { class: 'metrics' }, ...f.metrics.map((m) => h('div', {},
        h('dt', {}, m.label),
        h('dd', {}, h('span', { class: `value ${/^\d|^-\d/.test(m.value) ? 'num' : 'word'}` }, m.value), m.unit ? h('span', { class: 'unit' }, m.unit) : null,
          m.note ? h('span', { class: 'note' }, m.note) : null),
      ))),
    ),
    figure,
  );
  return art;
}

function evidenceFor(r: AnalysisResult, f: Finding, failed: boolean): HTMLElement | null {
  const fig = (render: (w: number) => SVGSVGElement, caption: Array<Node | string>, extraClass = '') => {
    const chart = h('div', { class: 'chart' });
    const el = h('figure', { class: `evidence ${extraClass}` }, chart, h('figcaption', {}, ...caption));
    queueMicrotask(() => responsive(chart, render));
    if (extraClass.includes('plate-figure')) {
      if (typeof IntersectionObserver === 'undefined') el.classList.add('revealed');
      else {
        const io = new IntersectionObserver((entries) => {
          if (entries.some((e) => e.isIntersecting)) { el.classList.add('revealed'); io.disconnect(); }
        }, { threshold: 0.35 });
        io.observe(el);
      }
    }
    return el;
  };
  switch (f.id) {
    case 'quality':
      if (!r.pre || !r.quality) return null;
      return fig((w) => timelineChart(r, w), [
        h('strong', {}, 'The whole recording. '),
        failed
          ? 'Each red mark is a heartbeat VasoScan found. Hatched stretches were disturbed and could not be used, which is why the recording failed.'
          : 'Each red mark is a heartbeat VasoScan found. Hatched stretches, if any, were left out of every measurement.',
      ]);
    case 'rate':
      return fig((w) => intervalsChart(r, w), [
        h('strong', {}, 'Time between beats. '),
        'Each dot is the time from one heartbeat to the next. Higher means slower. Gaps are where beats were left out.',
      ]);
    case 'shape':
      return fig((w) => heartbeatPlate(r, w), [
        h('strong', {}, r.provenance.kind === 'simulated' ? 'The average heartbeat. ' : 'Your average heartbeat. '),
        `The red line is the average of ${r.quality?.metrics.acceptedBeats} beats from this recording; the faint lines are individual beats. Each labelled point is something VasoScan measured.`,
      ], 'plate-figure');
    case 'stiffness':
      return fig((w) => stiffnessScale(r, w), [
        h('strong', {}, 'Where the indicator falls. '),
        'The marker is the indicator; the bracket is its likely range, based on how much the pulse shape varied between beats. The range does not include the larger uncertainty of the untrained model itself.',
      ]);
  }
}

function limitsBlock(simulated: boolean): HTMLElement {
  return h('section', { class: 'limits-panel', 'aria-labelledby': 'limits-r' },
    h('h2', { id: 'limits-r', class: 'section-title' }, 'What this reading cannot tell you'),
    h('ul', { class: 'limit-list' },
      h('li', {}, 'It is not a diagnosis. It cannot tell you whether your heart or arteries are healthy.'),
      h('li', {}, 'It cannot detect narrowed or blocked arteries, measure blood pressure, or assess heart rhythm.'),
      h('li', {}, 'A single one-minute reading reflects this moment: posture, temperature, caffeine, stress and finger pressure all change it.'),
      h('li', {}, 'If you have symptoms such as chest pain, breathlessness, fainting or palpitations, contact a health professional.'),
      simulated ? h('li', {}, 'These results come from a simulated recording and describe a model, not a person.') : null,
    ),
  );
}

function technicalSection(r: AnalysisResult): HTMLElement {
  const items: HTMLElement[] = [];
  const pre = r.pre!;
  const block = (title: string, sub: string, what: string, why: string, render?: (w: number) => SVGSVGElement, extra?: Node) => {
    const body = h('div', { class: 'd-body' });
    const det = h('details', { class: 'disclose' },
      h('summary', {}, h('span', {}, h('span', { class: 's-title' }, title), h('span', { class: 's-sub' }, sub)), chev()),
      body);
    let drawn = false;
    det.addEventListener('toggle', () => {
      if (!det.open || drawn) return;
      drawn = true;
      if (render) {
        const chart = h('div', { class: 'chart' });
        body.append(h('figure', { class: 'evidence' }, chart));
        responsive(chart, render);
      }
      body.append(h('div', { class: 'tech-notes' },
        h('p', {}, h('strong', {}, 'What you are seeing. '), what),
        h('p', {}, h('strong', {}, 'Why it matters. '), why)));
      if (extra) body.append(extra);
    });
    items.push(det);
  };

  const pulsePct = r.perfusionIndexPct;
  block('Raw camera brightness', 'The signal before any processing',
    `The average ${pre.channel} brightness of each camera frame.${pulsePct ? ` The small ripples are your pulse, about ${pulsePct.toFixed(1)}% of the total light.` : ''} Dashed lines mark ${pre.exposureSteps.length} automatic camera brightness changes, which were corrected.`,
    'It shows exactly what the camera delivered, so every later step can be checked against it.',
    (w) => rawChart(r, state.frames, w));

  block('Filtered signal and detected heartbeats', 'Beat detection across the recording',
    'The signal after removing slow drift and fast noise (keeping 0.5–4 Hz). Red dots are detected heartbeats; open dots fell in stretches that were left out, shown hatched.',
    'Every timing measurement starts from these detected beats.',
    (w) => signalChart(r, w));

  if (r.quality?.pass) {
    block('Frequency spectrum', 'An independent check on heart rate',
      `How strongly each rhythm is present in the signal. The tallest peak is the heart rate${r.hrv ? `; the beat-by-beat average was ${Math.round(r.hrv.heartRateBpm)} beats/min` : ''}.`,
      'Two different methods giving the same heart rate is evidence the beats were detected correctly.',
      (w) => spectrumChart(r, w));
  }

  if (r.ensemble) {
    const e = r.ensemble;
    block('All beats and their average', 'How the average heartbeat is built',
      `${e.beats.length} beats lined up on their steepest rising point. Grey lines were used; red-brown lines were rejected as outliers. The bold red line is the average. Split-half reproducibility: ${e.splitHalfR.toFixed(3)}.`,
      'A single camera heartbeat is too noisy to measure. Averaging many aligned beats cancels random noise and keeps the shape they share.',
      (w) => ensembleChart(r, w));
  }

  if (r.morphology) {
    block('Acceleration waveform (APG)', 'Second derivative of the average beat',
      'The rate of change of the slope of the average beat. Research literature labels its waves a to e and uses their ratios, such as b/a and d/a, to describe pulse shape.',
      'The aging index, (b − c − d − e)/a, is one input to the stiffness indicator. Phone cameras sample only about 30 times a second, which shifts these ratios compared with clinical sensors, so values here are not comparable with published reference values.',
      (w) => apgChart(r, w));
  }

  block('All measurements', 'Every value with its likely range and method', 'Every number the analysis produced, with its likely range from resampling the beats where one was computed.', 'Research users can check each value and how it was obtained.', undefined, measurementsTable(r));
  block('Processing record', 'Settings and corrections for this recording', 'The technical conditions of this recording and the corrections applied.', 'Needed to reproduce the analysis or to compare recordings.', undefined, processingTable(r));
  block('Download data', 'Recording and results as files', 'The recording contains per-frame brightness values with timestamps, not video.', 'Lets the analysis be repeated or examined with other tools.', undefined, downloadButtons(r));

  return h('section', { class: 'technical', 'aria-labelledby': 'tech-title' },
    h('h2', { id: 'tech-title', class: 'section-title' }, 'How this was measured'),
    h('p', { class: 'section-lede' }, 'The evidence behind every finding, step by step. Open any section to inspect it.'),
    h('div', { class: 'disclosures' }, ...items));
}

function table(headers: string[], rows: Array<Array<string>>): HTMLElement {
  return h('div', { class: 'table-scroll' }, h('table', { class: 'sr-table' },
    h('thead', {}, h('tr', {}, ...headers.map((x) => h('th', { scope: 'col' }, x)))),
    h('tbody', {}, ...rows.map((row) => h('tr', {}, ...row.map((c, i) => (i === 0 ? h('th', { scope: 'row' }, c) : h('td', { class: /^[-\d]/.test(c) ? 'n' : '' }, c))))))));
}

function measurementsTable(r: AnalysisResult): HTMLElement {
  const m = r.morphology, u = r.score?.uncertainty, hv = r.hrv;
  const f = (v: number | null | undefined, d = 0) => (v === null || v === undefined || !Number.isFinite(v) ? '–' : v.toFixed(d));
  const iv = (x: { lo: number; hi: number } | null | undefined, d = 0) => (x ? `${x.lo.toFixed(d)} to ${x.hi.toFixed(d)}` : '–');
  const rows: string[][] = [
    ['Heart rate', `${f(hv?.heartRateBpm, 1)} beats/min`, '–', 'Mean of valid beat intervals'],
    ['RMSSD', `${f(hv?.rmssdMs)} ms`, '–', hv?.rmssdAboveNoise ? 'Successive differences, clean pairs only' : `Below resolvable level (noise floor ≈ ${f(hv?.rmssdNoiseFloorMs)} ms)`],
    ['SDNN', `${f(hv?.sdnnMs)} ms`, '–', 'Ultra-short (≈1 min); not comparable with 5-min SDNN'],
    ['Crest time', `${f(m?.crestTimeMs)} ms`, iv(u?.features.crestTimeMs), 'Tangent foot to systolic peak'],
    ['Crest time / beat', `${f((m?.crestTimeRatio ?? NaN) * 100, 1)} %`, '–', ''],
    ['Reflection index', `${f(m?.reflectionIndexPct)} %`, iv(u?.features.reflectionIndexPct), 'Diastolic ÷ systolic height'],
    ['ΔT peak to reflected wave', `${f(m?.deltaTMs)} ms`, '–', m?.diastolic ? `Diastolic ${m.diastolic.method}` : 'Not measurable'],
    ['Stiffness index SI', `${f(m?.stiffnessIndex, 1)} m/s`, iv(u?.features.stiffnessIndex, 1), 'Height ÷ ΔT (Millasseau 2002)'],
    ['APG b/a', f(m?.apg?.ba, 2), iv(u?.features.ba, 2), ''],
    ['APG d/a', f(m?.apg?.da, 2), iv(u?.features.da, 2), m?.apg && !m.apg.cdResolved ? 'c and d merged; estimated' : ''],
    ['Aging index', f(m?.apg?.agi, 2), iv(u?.features.agi, 2), '(b − c − d − e)/a (Takazawa 1998)'],
    ['Perfusion index', `${f(r.perfusionIndexPct, 2)} %`, '–', 'Relative to this phone’s camera'],
    ['Stiffness indicator', f(r.score?.score), iv(u?.score), r.score ? `${r.score.modelVersion}` : ''],
  ];
  return table(['Measure', 'Value', 'Likely range (90%)', 'Method'], rows);
}

function processingTable(r: AnalysisResult): HTMLElement {
  const pre = r.pre!, q = r.quality!;
  const rows: string[][] = [
    ['Frames analysed', String(state.frames.length)],
    ['Frame rate', `${q.metrics.frameRate.toFixed(2)} frames/s`],
    ['Timestamp source', state.meta?.timebase ?? (r.provenance.kind === 'simulated' ? 'Simulated' : '–')],
    ['Flashlight', state.meta?.torch ?? (r.provenance.kind === 'simulated' ? 'Simulated' : '–')],
    ['Colour channel used', pre.channel],
    ['Settling time discarded', `${r.analysisOffsetSec.toFixed(1)} s`],
    ['Exposure changes corrected', String(pre.exposureSteps.length)],
    ['Glitch frames replaced', String(pre.glitchFrames)],
    ['Detection band', '0.5–4 Hz, zero-phase Butterworth'],
    ['Morphology band', `0.4–${pre.morphHigh.toFixed(1)} Hz`],
    ['Split-half reproducibility', q.metrics.splitHalfR.toFixed(3)],
    ['Spectral concentration', q.metrics.spectralConcentration.toFixed(2)],
    ['Beat timing noise estimate', r.hrv?.timingNoiseMs ? `${r.hrv.timingNoiseMs.toFixed(1)} ms` : '–'],
    ['Quality score', `${q.score} / 100`],
    ['Model', r.score?.modelVersion ?? 'Not run'],
  ];
  return table(['Item', 'Value'], rows);
}

function downloadButtons(r: AnalysisResult): HTMLElement {
  const save = (name: string, data: unknown) => {
    const blob = new Blob([JSON.stringify(data)], { type: 'application/json' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = name;
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 5000);
  };
  const stamp = r.analysedAt.replace(/[:.]/g, '-');
  return h('div', { class: 'actions' },
    h('button', { class: 'btn secondary', onclick: () => save(`vasoscan-recording-${stamp}.json`, { version: 1, meta: state.meta ?? { provenance: r.provenance }, frames: state.frames }) }, icon('download'), 'Download recording'),
    h('button', { class: 'btn secondary', onclick: () => save(`vasoscan-results-${stamp}.json`, resultsExport(r)) }, icon('download'), 'Download results'),
  );
}

function resultsExport(r: AnalysisResult) {
  return {
    provenance: r.provenance, analysedAt: r.analysedAt, subject: r.subject,
    summary: summarise(r), findings: allFindings(r),
    quality: r.quality && { pass: r.quality.pass, score: r.quality.score, issues: r.quality.issues, metrics: r.quality.metrics, artifacts: r.quality.artifacts },
    hrv: r.hrv, perfusionIndexPct: r.perfusionIndexPct,
    morphology: r.morphology && { ...r.morphology, contour: Array.from(r.morphology.contour), d1: undefined, d2: undefined },
    score: r.score,
  };
}

function actionsRow(ctx: Ctx, simulated: boolean): HTMLElement {
  return h('div', { class: 'actions results-actions' },
    h('button', { class: 'btn', onclick: () => ctx.go('setup') }, icon('camera'), simulated ? 'Record your own pulse' : 'Record again'),
    h('button', { class: 'btn secondary', onclick: () => ctx.go('demo') }, simulated ? 'Try another demo' : 'View a demo recording'),
  );
}
